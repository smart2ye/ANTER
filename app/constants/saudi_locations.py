def cities_for_region(region: str) -> list[str]:
    """يعيد قائمة مدن منطقة معينة (سعودية أو يمنية)."""
    return SAUDI_REGIONS.get(region) or YEMEN_REGIONS.get(region) or []


def all_regions() -> list[str]:
    """يعيد كل المناطق (السعودية أولاً ثم اليمنية)."""
    return list(SAUDI_REGIONS.keys()) + list(YEMEN_REGIONS.keys())


def region_of_city(city: str) -> str | None:
    """يعيد اسم المنطقة لمدينة معينة (سعودية أو يمنية)."""
    for region, cities in SAUDI_REGIONS.items():
        if city in cities:
            return region
    for region, cities in YEMEN_REGIONS.items():
        if city in cities:
            return region
    return None


def country_of_region(region: str) -> str | None:
    """يعيد رمز الدولة ('SA' أو 'YE') لمنطقة معينة، أو None إن لم توجد."""
    if region in SAUDI_REGIONS:
        return 'SA'
    if region in YEMEN_REGIONS:
        return 'YE'
    return None
