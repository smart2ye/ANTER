def cities_for_region(region: str) -> list[str]:
    """يعيد قائمة مدن منطقة معينة."""
    return SAUDI_REGIONS.get(region, [])


def all_regions() -> list[str]:
    """يعيد كل المناطق."""
    return list(SAUDI_REGIONS.keys())


def region_of_city(city: str) -> str | None:
    """يعيد اسم المنطقة لمدينة معينة."""
    for region, cities in SAUDI_REGIONS.items():
        if city in cities:
            return region
    return None
